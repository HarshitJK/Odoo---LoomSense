MONGODB_DB_NAME = os.getenv("MONGODB_DB_NAME", "loomsense")
CORS_ORIGINS = [
    o.strip()
    for o in os.getenv("CORS_ORIGINS", "http://localhost:5173").split(",")
    if o.strip()
]
