from typing import Literal, Optional

from pydantic import BaseModel, Field

from app.utils.tokens import new_tracking_token


class OrderCosts(BaseModel):
    rawMaterial: float = 0
    labour: float = 0
    machine: float = 0
    rework: float = 0
    other: float = 0


class Order(BaseModel):
    trackingToken: str = Field(default_factory=new_tracking_token)
    orderId: str
    buyerId: Optional[str] = None
    buyerName: Optional[str] = None
    fabricType: Optional[str] = None
    colour: Optional[str] = None
    quantityMeters: float = 0
    producedMeters: float = 0
    status: str = "PENDING"
    orderDate: Optional[str] = None
    machineId: Optional[str] = None
    deadline: Optional[str] = None
    revenue: float = 0
    yarnBatch: Optional[str] = None  # batchId of the yarn used
    yarnConsumedKg: Optional[float] = None  # actual kg used; default = 0.59 x producedMeters
    otherCost: float = 0  # other production cost in INR
    paidAmount: float = 0  # buyer payments received (derived from transactions)
    costs: OrderCosts = OrderCosts()
    profit: Optional[float] = None
    margin: Optional[float] = None
    # stage-gated quality control (empty on old orders, which are not gated)
    currentStage: Optional[str] = None
    stageStatus: Optional[str] = None  # IN_PROGRESS | QC_PENDING | QUALITY_HOLD | COMPLETE
    pendingInspectionType: Optional[str] = None  # FIRST_OFF | STAGE | FINAL while QC_PENDING
    qualityHold: Optional[dict] = None
    productionBlocked: bool = False
    productionBlockReason: Optional[str] = None
    requiresFirstOffQc: bool = True
    firstOffPassed: bool = False
    sampleMeters: float = 100


class OrderCreate(BaseModel):
    """Body for POST /api/orders. orderId is generated by the server."""
    buyerId: Optional[str] = None
    buyerName: str = Field(min_length=1)
    fabricType: Optional[str] = None
    colour: Optional[str] = None
    quantityMeters: float = Field(gt=0)
    machineId: Optional[str] = None
    deadline: Optional[str] = None
    revenue: float = Field(default=0, ge=0)
    yarnBatch: Optional[str] = None
    otherCost: float = 0
    status: str = "NEW"


class OrderUpdate(BaseModel):
    """Body for PATCH /api/orders/{id}. Send only the fields to change."""
    buyerId: Optional[str] = None
    buyerName: Optional[str] = None
    fabricType: Optional[str] = None
    colour: Optional[str] = None
    quantityMeters: Optional[float] = Field(default=None, gt=0)
    producedMeters: Optional[float] = Field(default=None, ge=0)
    status: Optional[str] = None
    machineId: Optional[str] = None
    deadline: Optional[str] = None
    revenue: Optional[float] = Field(default=None, ge=0)
    yarnBatch: Optional[str] = None
    yarnConsumedKg: Optional[float] = Field(default=None, ge=0)
    otherCost: Optional[float] = Field(default=None, ge=0)
    requiresFirstOffQc: Optional[bool] = None
    sampleMeters: Optional[float] = Field(default=None, gt=0)


class ReadinessRequest(BaseModel):
    """Body for POST /api/orders/readiness-check (order does not need to exist)."""
    quantityMeters: float = Field(gt=0)
    colour: str
    fabricType: str
    expectedRevenue: float = Field(default=0, ge=0)


PauseReason = Literal["MACHINE_BREAKDOWN", "MAINTENANCE", "MATERIAL_SHORTAGE", "QUALITY_ISSUE", "OPERATOR_UNAVAILABLE", "MANUAL", "OTHER"]
CancelReason = Literal["BUYER_CANCELLED", "MATERIAL_ISSUE", "PRODUCTION_DEFECT", "MACHINE_LIMITATIONS", "COMMERCIAL_DECISION",
                       "DUPLICATE_ORDER", "OTHER"]


class PauseRequest(BaseModel):
    """Body for POST /api/orders/{id}/pause."""
    reason: PauseReason
    notes: Optional[str] = Field(default=None, max_length=1000)


class ResumeRequest(BaseModel):
    """Body for POST /api/orders/{id}/resume. Without machineId the paused machine(s) are used again."""
    machineId: Optional[str] = None


class ChangeMachineRequest(BaseModel):
    """Body for POST /api/orders/{id}/change-machine."""
    newMachineId: str = Field(min_length=1)
    reason: PauseReason
    notes: Optional[str] = Field(default=None, max_length=1000)


class CancelRequest(BaseModel):
    """Body for POST /api/orders/{id}/cancel."""
    reason: CancelReason
    notes: Optional[str] = Field(default=None, max_length=1000)
