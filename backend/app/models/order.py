from typing import Optional

from pydantic import BaseModel


class OrderCosts(BaseModel):
    rawMaterial: float = 0
    labour: float = 0
    machine: float = 0
    rework: float = 0
    other: float = 0


class Order(BaseModel):
    orderId: str
    buyerId: Optional[str] = None
    buyerName: Optional[str] = None
    fabricType: Optional[str] = None
    colour: Optional[str] = None
    quantityMeters: float = 0
    producedMeters: float = 0
    status: str = "PENDING"
    orderDate: Optional[str] = None
    machineId: Optional[str] = None
    deadline: Optional[str] = None
    revenue: float = 0
    yarnBatch: Optional[str] = None  # batchId of the yarn used
    yarnConsumedKg: Optional[float] = None  # actual kg used; default = 0.59 x producedMeters
    otherCost: float = 0  # other production cost in INR
    costs: OrderCosts = OrderCosts()
    profit: Optional[float] = None
    margin: Optional[float] = None


class OrderCreate(BaseModel):
    """Body for POST /api/orders. orderId is generated by the server."""
    buyerId: Optional[str] = None
    buyerName: str
    fabricType: Optional[str] = None
    colour: Optional[str] = None
    quantityMeters: float
    machineId: Optional[str] = None
    deadline: Optional[str] = None
    revenue: float = 0
    yarnBatch: Optional[str] = None
    otherCost: float = 0
    status: str = "NEW"


class OrderUpdate(BaseModel):
    """Body for PATCH /api/orders/{id}. Send only the fields to change."""
    buyerId: Optional[str] = None
    buyerName: Optional[str] = None
    fabricType: Optional[str] = None
    colour: Optional[str] = None
    quantityMeters: Optional[float] = None
    producedMeters: Optional[float] = None
    status: Optional[str] = None
    machineId: Optional[str] = None
    deadline: Optional[str] = None
    revenue: Optional[float] = None
    yarnBatch: Optional[str] = None
    yarnConsumedKg: Optional[float] = None
    otherCost: Optional[float] = None


class ReadinessRequest(BaseModel):
    """Body for POST /api/orders/readiness-check (order does not need to exist)."""
    quantityMeters: float
    colour: str
    fabricType: str
    expectedRevenue: float = 0
